function getLang() {
    const saved = localStorage.getItem(I18N_LS_KEY);
    return I18N[saved] ? saved : I18N_DEFAULT_LANG;
}

function setLang(lang) {
    if (!I18N[lang]) return;
    localStorage.setItem(I18N_LS_KEY, lang);
    location.reload();
}

function t(key, vars) {
    const lang = getLang();
    let str = I18N[lang]?.[key] ?? I18N[I18N_DEFAULT_LANG]?.[key] ?? key;
    if (vars) {
        Object.entries(vars).forEach(([k, v]) => { str = str.replaceAll(`{${k}}`, v); });
    }
    return str;
}

// Aplica traduções a HTML estático marcado com data-i18n / data-i18n-placeholder / data-i18n-title.
function applyStaticTranslations(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}
